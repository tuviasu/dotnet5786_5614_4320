using DalApi;

namespace Helpers
{
    internal static class OrderManager
    {
        internal static ObserverManager Observers = new(); //stage 5 
        private static readonly IDal dal = DalApi.Factory.Get;

        // =============================================================
        // Convert DO.Order → BO.OrderInList
        // =============================================================
        internal static BO.OrderInList ConvertToOrderInList(DO.Order order)
        {
            var deliveries = dal.Delivery.ReadAll(d => d?.OrderedId == order.Id).ToList();

            var lastDelivery = deliveries.OrderByDescending(d => d!.StartDelivery).FirstOrDefault();

            return new BO.OrderInList
            {
                OrderId = order.Id,
                DeliverId = lastDelivery?.Id,
                Type = (BO.OrderType)order.Type, // Explicit cast added here
                AirDistance = Tools.AirDistance(
                    order.Latitude,
                    order.Longitude,
                    dal.Config.Latitude ?? 0,
                    dal.Config.Longitude ?? 0
                ),
                Status = CalculateOrderStatus(order.Id),
                ScheduleStatus = CalculateScheduleStatus(order.Id),
                RemainingTime = dal.Config.MaxDeliveryTime - (AdminManager.Now - order.OrderDate),
                HandlingTime = lastDelivery?.EndDelivery != null
                    ? lastDelivery.EndDelivery.Value - lastDelivery.StartDelivery
                    : AdminManager.Now - lastDelivery?.StartDelivery ?? TimeSpan.Zero,
                DeliveriesCount = deliveries.Count
            };
        }

        // =============================================================
        // Convert DO.Order → BO.Order (full object)
        // =============================================================
        internal static BO.Order ConvertToOrder(DO.Order order)
        {
            var deliveries = dal.Delivery.ReadAll(d => d?.OrderedId == order.Id).ToList();

            return new BO.Order
            {
                Id = order.Id,
                CustomerName = order.CustomerName,
                CustomerPhone = order.CustomerPhone,
                FullAddressForDelivery = order.CustomerAddress,
                OrderDate = order.OrderDate,
                Type = (BO.OrderType)order.Type, // Explicit cast added here
                Status = CalculateOrderStatus(order.Id),
                ScheduleStatus_ = CalculateScheduleStatus(order.Id),
                DeliveriesHistory = deliveries
                    .Select(DeliveryManager.ConvertToDeliveryInOrder)
                    .ToList()
            };
        }

        // =============================================================
        // CRUD Operations
        // =============================================================
        internal static void CreateOrder(int requesterId, BO.Order order)
        {
            dal.Order.Create(new DO.Order
            {
                Id = dal.Config.NextOrderId,
                Type = (DO.OrderType)(order.Type ?? BO.OrderType.Regular), // Explicit cast to DO.OrderType
                Latitude = 0,
                Longitude = 0,
                CustomerName = order.CustomerName,
                CustomerAddress = order.FullAddressForDelivery,
                CustomerPhone = order.CustomerPhone,
                OrderDate = AdminManager.Now
            });

            Observers.NotifyListUpdated(); //stage 5
        }

        internal static BO.Order GetOrder(int requesterId, int orderId)
        {
            var doOrder = dal.Order.Read(orderId)
                ?? throw new BO.BlDoesNotExistException("Order not found");

            return ConvertToOrder(doOrder);
        }

        internal static IEnumerable<BO.OrderInList> GetOrders(
            int requesterId,
            BO.OrderInListFilterBy? filterBy,
            object? filterValue,
            BO.OrderInListSortBy? sortBy)
        {
            var orders = dal.Order.ReadAll().Select(o => ConvertToOrderInList(o!));

            if (filterBy != null && filterValue != null)
            {
                orders = filterBy switch
                {
                    BO.OrderInListFilterBy.Status =>
                        orders.Where(o => o.Status == (BO.OrderStatus)filterValue),

                    BO.OrderInListFilterBy.OnTimeStatus =>
                        orders.Where(o => o.ScheduleStatus == (BO.ScheduleStatus)filterValue),

                    _ => orders
                };
            }

            if (sortBy != null)
            {
                orders = sortBy switch
                {
                    BO.OrderInListSortBy.Id => orders.OrderBy(o => o.OrderId),
                    BO.OrderInListSortBy.Status => orders.OrderBy(o => o.Status),
                    BO.OrderInListSortBy.OnTimeStatus => orders.OrderBy(o => o.ScheduleStatus),
                    _ => orders
                };
            }

            return orders;
        }

        internal static void UpdateOrder(int requesterId, BO.Order order)
        {
            var existing = dal.Order.Read(order.Id)
                ?? throw new BO.BlDoesNotExistException("Order not found");

            dal.Order.Update(existing with
            {
                CustomerName = order.CustomerName,
                CustomerPhone = order.CustomerPhone,
                CustomerAddress = order.FullAddressForDelivery
            });

            Observers.NotifyItemUpdated(order.Id); //stage 5
            Observers.NotifyListUpdated(); //stage 5
        }

        internal static void DeleteOrder(int requesterId, int orderId)
        {
            throw new BO.BLIllegalActionException("Orders cannot be deleted manually.");
        }

        // =============================================================
        // Cancel Order
        // =============================================================
        internal static void CancelOrder(int requesterId, int orderId)
        {
            var status = CalculateOrderStatus(orderId);

            if (status == BO.OrderStatus.Delivered)
                throw new BO.BLIllegalActionException("Cannot cancel delivered order");

            dal.Delivery.Create(new DO.Delivery(
                Id: dal.Config.NextOrderId,
                OrderedId: orderId,
                CourierId: 0,
                DeliveryType: DO.DeliveryTransport.Foot,
                StartDelivery: AdminManager.Now,
                EndDelivery: AdminManager.Now,
                CompletionType: DO.DeliveryCompletionType.Canceled
            ));

            Observers.NotifyItemUpdated(orderId); //stage 5
            Observers.NotifyListUpdated(); //stage 5
        }

        // =============================================================
        // Take Order for Treatment
        // =============================================================
        internal static void TakeOrder(int requesterId, int courierId, int orderId)
        {
            var status = CalculateOrderStatus(orderId);
            if (status != BO.OrderStatus.Created)
                throw new BO.BLIllegalActionException("Order is not available for pickup");

            dal.Delivery.Create(new DO.Delivery(
                Id: dal.Config.NextOrderId,
                OrderedId: orderId,
                CourierId: courierId,
                DeliveryType: DO.DeliveryTransport.Motorcycle,
                StartDelivery: AdminManager.Now
            ));

            Observers.NotifyItemUpdated(orderId); //stage 5
            Observers.NotifyListUpdated(); //stage 5
        }

        // =============================================================
        // Summary for admin dashboard (READ ONLY)
        // =============================================================
        internal static int[] GetOrdersSummary(int requesterId)
        {
            var arr = new int[4];
            foreach (var o in dal.Order.ReadAll())
            {
                var status = CalculateOrderStatus(o!.Id);
                arr[(int)status]++;
            }
            return arr;
        }

        // =============================================================
        // Assign order to courier
        // =============================================================
        internal static void AssignOrderToCourier(int requesterId, int courierId, int orderId)
        {
            var order = dal.Order.Read(orderId)
                ?? throw new BO.BlDoesNotExistException("Order not found.");

            var status = CalculateOrderStatus(orderId);
            if (status != BO.OrderStatus.Created)
                throw new BO.BLIllegalActionException("Order is not available for assignment.");

            var courier = dal.Courier.Read(courierId)
                ?? throw new BO.BlDoesNotExistException("Courier not found.");

            var newDelivery = new DO.Delivery(
                Id: dal.Config.NextOrderId,
                OrderedId: orderId,
                CourierId: courierId,
                DeliveryType: courier.Transport,
                StartDelivery: AdminManager.Now
            );

            dal.Delivery.Create(newDelivery);

            Observers.NotifyItemUpdated(orderId); //stage 5
            Observers.NotifyListUpdated(); //stage 5
        }

        // Add this method to OrderManager to fix CS0103
        private static BO.OrderStatus CalculateOrderStatus(int orderId)
        {
            var deliveries = dal.Delivery.ReadAll(d => d?.OrderedId == orderId).ToList();
            if (deliveries.Count == 0)
                return BO.OrderStatus.Created;

            var lastDelivery = deliveries.OrderByDescending(d => d!.StartDelivery).FirstOrDefault();
            if (lastDelivery?.CompletionType == DO.DeliveryCompletionType.Canceled)
                return BO.OrderStatus.Cancelled;
            if (lastDelivery?.EndDelivery != null)
                return BO.OrderStatus.Delivered;
            return BO.OrderStatus.Shipping;
        }

        // Add this method to OrderManager to fix CS0103
        private static BO.ScheduleStatus CalculateScheduleStatus(int orderId)
        {
            var deliveries = dal.Delivery.ReadAll(d => d?.OrderedId == orderId).ToList();
            if (deliveries.Count == 0)
                return BO.ScheduleStatus.Pending;

            var lastDelivery = deliveries.OrderByDescending(d => d!.StartDelivery).FirstOrDefault();
            if (lastDelivery?.CompletionType == DO.DeliveryCompletionType.Canceled)
                return BO.ScheduleStatus.Cancelled;
            if (lastDelivery?.EndDelivery != null)
                return BO.ScheduleStatus.Completed;
            return BO.ScheduleStatus.InProgress;
        }
    }
